// Command genhuffman converts Huffman-compressed sample headers -- the
// ones Mozzi's extras/python/audio2huff.py makes, e.g.
// Mozzi/samples/thumbpiano_huffman/*.h -- into a Go package for
// mozzi/samplehuffman, backed by //go:embed binary blobs like
// tools/gentables' wavetables.
//
// Each header holds three things for a sample NAME: NAME_HUFFMAN (int16
// decoding tree), NAME_SOUNDDATA (uint8 bit stream) and NAME_SOUNDDATA_BITS
// (its length in bits), plus NAME_SAMPLERATE. For each, the package gets
// NameHuffman ([]int16), NameSoundData ([]uint8), and NameSoundDataBits and
// NameSampleRate constants.
//
// Usage:
//
//	go run ./tools/genhuffman <dir of headers> <output package dir>
//
// e.g. go run ./tools/genhuffman ../Mozzi/samples/thumbpiano_huffman samples/thumbpianohuffman
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	reArray   = regexp.MustCompile(`CONSTTABLE_STORAGE\(\s*(\w+)\s*\)\s*(\w+)_(HUFFMAN|SOUNDDATA)\s*\[[^\]]*\]\s*=\s*\{([^}]*)\}`)
	reBits    = regexp.MustCompile(`(\w+)_SOUNDDATA_BITS\s*=\s*(\d+)`)
	reRate    = regexp.MustCompile(`(?m)^#define\s+(\w+)_SAMPLERATE\s+(\d+)`)
	reNumber  = regexp.MustCompile(`-?\d+`)
	reComment = regexp.MustCompile(`(?s)/\*.*?\*/|//[^\n]*`)
)

type sample struct {
	stem, prefix, goName string
	huffman              []int64
	soundData            []int64
	bits, rate           int
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: genhuffman <dir of audio2huff headers> <output package dir>")
		os.Exit(2)
	}
	srcDir, outDir := os.Args[1], os.Args[2]
	pkg := filepath.Base(outDir)
	shownDir := strings.TrimLeft(filepath.ToSlash(filepath.Clean(srcDir)), "./") // e.g. "Mozzi/samples/thumbpiano_huffman"

	files, err := filepath.Glob(filepath.Join(srcDir, "*.h"))
	check(err)
	sort.Strings(files)
	if len(files) == 0 {
		fatalf("no .h files in %s", srcDir)
	}
	check(os.MkdirAll(filepath.Join(outDir, "sampledata"), 0o755))

	var docLines []string
	for _, f := range files {
		src, err := os.ReadFile(f)
		check(err)
		s := parse(filepath.Base(f), reComment.ReplaceAllString(string(src), ""))
		writeBin(filepath.Join(outDir, "sampledata", s.stem+"_huffman.bin"), s.huffman, 2)
		writeBin(filepath.Join(outDir, "sampledata", s.stem+"_sounddata.bin"), s.soundData, 1)
		writeGo(filepath.Join(outDir, s.stem+".go"), pkg, shownDir, s)
		docLines = append(docLines, fmt.Sprintf("//   - %s (%d bytes of sound data, %dHz) from %s.h", s.goName, len(s.soundData), s.rate, s.stem))
	}
	writeSupport(outDir, pkg, shownDir, docLines)
}

func parse(name, src string) *sample {
	s := &sample{stem: strings.TrimSuffix(name, ".h")}
	for _, m := range reArray.FindAllStringSubmatch(src, -1) {
		cType, prefix, kind, body := m[1], m[2], m[3], m[4]
		if s.prefix != "" && prefix != s.prefix {
			fatalf("%s: arrays for both %s and %s", name, s.prefix, prefix)
		}
		s.prefix = prefix
		var vals []int64
		for _, n := range reNumber.FindAllString(body, -1) {
			v, err := strconv.ParseInt(n, 10, 64)
			check(err)
			vals = append(vals, v)
		}
		switch {
		case kind == "HUFFMAN" && cType == "int16_t":
			s.huffman = vals
		case kind == "SOUNDDATA" && cType == "uint8_t":
			s.soundData = vals
		default:
			fatalf("%s: unexpected %s array of type %s", name, kind, cType)
		}
	}
	if s.huffman == nil || s.soundData == nil {
		fatalf("%s: missing _HUFFMAN or _SOUNDDATA array", name)
	}
	m := reBits.FindStringSubmatch(src)
	if m == nil || m[1] != s.prefix {
		fatalf("%s: missing %s_SOUNDDATA_BITS", name, s.prefix)
	}
	s.bits, _ = strconv.Atoi(m[2])
	if (s.bits+7)/8 > len(s.soundData) {
		fatalf("%s: %d bits don't fit in %d bytes of sound data", name, s.bits, len(s.soundData))
	}
	if m := reRate.FindStringSubmatch(src); m != nil && m[1] == s.prefix {
		s.rate, _ = strconv.Atoi(m[2])
	}
	for _, part := range strings.Split(strings.ToLower(s.prefix), "_") {
		if part != "" {
			s.goName += strings.ToUpper(part[:1]) + part[1:]
		}
	}
	return s
}

func writeBin(path string, vals []int64, size int) {
	b := make([]byte, 0, len(vals)*size)
	for _, v := range vals {
		b = append(b, byte(v))
		if size == 2 {
			b = append(b, byte(v>>8))
		}
	}
	check(os.WriteFile(path, b, 0o644))
}

func writeGo(path, pkg, srcDir string, s *sample) {
	n := s.goName
	src := fmt.Sprintf(`// Code generated by tools/genhuffman from %[1]s/%[2]s.h; DO NOT EDIT.

package %[3]s

import _ "embed"

// %[4]sSampleRate is the rate %[4]s was recorded at: play it from UpdateAudio
// at this audio rate for its original pitch.
const %[4]sSampleRate = %[5]d

// %[4]sSoundDataBits is the number of valid bits in %[4]sSoundData.
const %[4]sSoundDataBits = %[6]d

// %[4]sSoundData is the Huffman-coded sound (flash-resident, via go:embed).
//
//go:embed sampledata/%[2]s_sounddata.bin
var %[4]sSoundData []byte

//go:embed sampledata/%[2]s_huffman.bin
var %[7]sHuffmanBytes []byte

// %[4]sHuffman is the decoding tree for %[4]sSoundData.
var %[4]sHuffman = asInt16LE(%[7]sHuffmanBytes)
`, filepath.ToSlash(srcDir), s.stem, pkg, n, s.rate, s.bits, strings.ToLower(n[:1])+n[1:])
	check(os.WriteFile(path, []byte(src), 0o644))
}

func writeSupport(outDir, pkg, srcDir string, docLines []string) {
	doc := fmt.Sprintf(`// Code generated by tools/genhuffman; DO NOT EDIT.

// Package %s holds Huffman-compressed samples for mozzi/samplehuffman,
// converted by tools/genhuffman from upstream Mozzi's %s:
//
%s
//
// Play one with samplehuffman.New(NameSoundData, NameHuffman, NameSoundDataBits).
package %s

// asInt16LE copies a little-endian byte blob into an []int16. The Huffman
// trees are small, so a RAM copy is cheaper than worrying about the
// alignment of an embedded blob.
func asInt16LE(b []byte) []int16 {
	out := make([]int16, len(b)/2)
	for i := range out {
		out[i] = int16(uint16(b[2*i]) | uint16(b[2*i+1])<<8)
	}
	return out
}
`, pkg, filepath.ToSlash(srcDir), strings.Join(docLines, "\n"), pkg)
	check(os.WriteFile(filepath.Join(outDir, "doc.go"), []byte(doc), 0o644))
}

func check(err error) {
	if err != nil {
		fatalf("%v", err)
	}
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genhuffman: "+format+"\n", args...)
	os.Exit(1)
}
